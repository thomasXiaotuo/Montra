export const supportedLanguages = ['zh','en'];
export const localeFor = language => language === 'zh' ? 'zh-CN' : 'en-US';
export function detectLanguage(saved, browserLanguages = []) {
  if (supportedLanguages.includes(saved)) return saved;
  for (const item of browserLanguages) {
    if (/^zh(?:-|$)/i.test(item)) return 'zh';
    if (/^en(?:-|$)/i.test(item)) return 'en';
  }
  return 'en';
}
export function translate(key, args = {}, language = 'en') {
  const template = messages[language]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => args[name] === undefined ? match : String(args[name]));
}
export function messageKey(value) {
  if (Object.hasOwn(messages.zh,value)) return value;
  return Object.keys(messages.en).find(key => messages.en[key] === value || messages.zh[key] === value) ?? value;
}
